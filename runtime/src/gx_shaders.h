/* The GX "ubershaders": one vertex and one fragment shader that read the raw XF/BP register state
 * (GxUniforms, std140 block "GX") and emulate the XF stage (matrices, lighting, texgen) and the TEV.
 * Shared by the backends; each prepends its own #version line (GL 3.3 core / deko3d GLSL 4.60).
 * Register semantics: YAGCD, Dolphin's VideoCommon (XFMemory.h, BPMemory.h, UberShader*). */
#pragma once

#define GX_SHADER_COMMON \
"layout(std140) uniform GX { uvec4 bp[64]; uvec4 xfr[32]; uvec4 xfm[416]; uvec4 konst[2]; };\n" \
"uint BP(int i) { return bp[i >> 2][i & 3]; }\n" \
"uint XR(int i) { return xfr[i >> 2][i & 3]; }\n" \
"float XM(int i) { return uintBitsToFloat(xfm[i >> 2][i & 3]); }\n" \
"uint XMU(int i) { return xfm[i >> 2][i & 3]; }\n" \
"uint KR(int i) { return konst[i >> 2][i & 3]; }\n" \
"uint bits(uint v, int s, int n) { return (v >> uint(s)) & ((1u << uint(n)) - 1u); }\n" \
"vec4 rgba8(uint c) { return vec4(float((c >> 24) & 255u), float((c >> 16) & 255u), float((c >> 8) & 255u), float(c & 255u)) / 255.0; }\n"

static const char* const k_gx_vertex_shader =
GX_SHADER_COMMON
"in vec4 a_pos; in vec4 a_nrm; in vec4 a_col0; in vec4 a_col1;\n"
"in vec4 a_tex01; in vec4 a_tex23; in vec4 a_tex45; in vec4 a_tex67; in vec4 a_tm0; in vec4 a_tm1;\n"
"out vec4 v_col0; out vec4 v_col1;\n"
"out vec3 v_tex0; out vec3 v_tex1; out vec3 v_tex2; out vec3 v_tex3;\n"
"out vec3 v_tex4; out vec3 v_tex5; out vec3 v_tex6; out vec3 v_tex7;\n"
"vec4 row(int a) { return vec4(XM(a), XM(a + 1), XM(a + 2), XM(a + 3)); }\n"
"vec3 lights(uint ctrl, vec3 pos, vec3 n, vec4 amb, bool alpha) {\n"
"  vec4 sum = amb;\n"
"  uint mask = bits(ctrl, 2, 4) | (bits(ctrl, 11, 4) << 4);\n"
"  uint diff_fn = bits(ctrl, 7, 2); bool atten = bits(ctrl, 9, 1) != 0u; bool spot = bits(ctrl, 10, 1) != 0u;\n"
"  for (int i = 0; i < 8; i++) {\n"
"    if ((mask & (1u << uint(i))) == 0u) continue;\n"
"    int b = 0x600 + i * 16;\n"
"    vec4 lc = rgba8(XMU(b + 3));\n"
"    vec3 ca = vec3(XM(b + 4), XM(b + 5), XM(b + 6)), da = vec3(XM(b + 7), XM(b + 8), XM(b + 9));\n"
"    vec3 lp = vec3(XM(b + 10), XM(b + 11), XM(b + 12)), ld = vec3(XM(b + 13), XM(b + 14), XM(b + 15));\n"
"    vec3 l; float att = 1.0;\n"
"    if (atten && spot) {\n"
"      l = lp - pos; float d2 = dot(l, l); float d = sqrt(d2); l = l / max(d, 1e-6);\n"
"      float c = max(0.0, dot(l, ld));\n"
"      att = max(0.0, ca.x + ca.y * c + ca.z * c * c) / max(1e-6, da.x + da.y * d + da.z * d2);\n"
"    } else if (atten) {\n"
"      l = normalize(lp);\n"
"      float c = dot(n, l) >= 0.0 ? max(0.0, dot(n, ld)) : 0.0;\n"
"      att = max(0.0, ca.x + ca.y * c + ca.z * c * c) / max(1e-6, da.x + da.y * c + da.z * c * c);\n"
"    } else {\n"
"      l = normalize(lp - pos);\n"
"    }\n"
"    float df = dot(l, n);\n"
"    df = diff_fn == 0u ? 1.0 : (diff_fn == 1u ? df : max(0.0, df));\n"
"    sum += att * df * lc;\n"
"  }\n"
"  return alpha ? vec3(clamp(sum.a, 0.0, 1.0)) : clamp(sum.rgb, 0.0, 1.0);\n"
"}\n"
"vec4 channel(int c, vec4 vcol, vec3 pos, vec3 n) {\n"
"  uint cc = XR(0x0E + c), ac = XR(0x10 + c);\n"
"  vec4 matr = rgba8(XR(0x0C + c)), ambr = rgba8(XR(0x0A + c));\n"
"  vec3 mat = bits(cc, 0, 1) != 0u ? vcol.rgb : matr.rgb;\n"
"  float mata = bits(ac, 0, 1) != 0u ? vcol.a : matr.a;\n"
"  vec3 rgb = mat; float a = mata;\n"
"  if (bits(cc, 1, 1) != 0u) rgb = mat * lights(cc, pos, n, vec4(bits(cc, 6, 1) != 0u ? vcol.rgb : ambr.rgb, 0.0), false);\n"
"  if (bits(ac, 1, 1) != 0u) a = mata * lights(ac, pos, n, vec4(0.0, 0.0, 0.0, bits(ac, 6, 1) != 0u ? vcol.a : ambr.a), true).x;\n"
"  return vec4(rgb, a);\n"
"}\n"
"vec3 texgen(int i, vec3 pos_raw, vec3 n, vec4 c0, vec4 c1, float tmtx) {\n"
"  uint info = XR(0x40 + i);\n"
"  uint src = bits(info, 7, 5), type = bits(info, 4, 3);\n"
"  vec4 s;\n"
"  if (src == 0u) s = vec4(pos_raw, 1.0);\n"
"  else if (src <= 4u) s = vec4(n, 1.0);\n"
"  else {\n"
"    int k = int(src) - 5;\n"
"    vec4 t = k == 0 ? vec4(a_tex01.xy, 1, 1) : k == 1 ? vec4(a_tex01.zw, 1, 1) : k == 2 ? vec4(a_tex23.xy, 1, 1) :\n"
"             k == 3 ? vec4(a_tex23.zw, 1, 1) : k == 4 ? vec4(a_tex45.xy, 1, 1) : k == 5 ? vec4(a_tex45.zw, 1, 1) :\n"
"             k == 6 ? vec4(a_tex67.xy, 1, 1) : vec4(a_tex67.zw, 1, 1);\n"
"    s = t;\n"
"  }\n"
"  if (bits(info, 2, 1) == 0u) s.z = 1.0;  /* AB11 */\n"
"  vec3 c;\n"
"  if (type == 2u) c = vec3(c0.rg, 1.0);\n"
"  else if (type == 3u) c = vec3(c1.rg, 1.0);\n"
"  else if (type == 1u) c = vec3(s.xy, 1.0);  /* emboss: approximated by the source coordinate */\n"
"  else {\n"
"    int a = int(tmtx) * 4;\n"
"    if (bits(info, 1, 1) != 0u) c = vec3(dot(row(a), s), dot(row(a + 4), s), dot(row(a + 8), s));\n"
"    else c = vec3(dot(row(a), s), dot(row(a + 4), s), 1.0);\n"
"    if (bits(XR(0x12), 0, 1) != 0u) {  /* dual texture transform: post matrix */\n"
"      uint post = XR(0x50 + i);\n"
"      if (bits(post, 8, 1) != 0u) c = normalize(c);\n"
"      int p = 0x500 + int(bits(post, 0, 6)) * 4;\n"
"      vec4 cc = vec4(c, 1.0);\n"
"      c = vec3(dot(row(p), cc), dot(row(p + 4), cc), dot(row(p + 8), cc));\n"
"    }\n"
"  }\n"
"  return c;\n"
"}\n"
"void main() {\n"
"  int pm = int(a_pos.w) * 4;\n"
"  vec4 p4 = vec4(a_pos.xyz, 1.0);\n"
"  vec3 pv = vec3(dot(row(pm), p4), dot(row(pm + 4), p4), dot(row(pm + 8), p4));\n"
"  int nm = 0x400 + (int(a_pos.w) & 31) * 3;\n"
"  vec3 n = vec3(dot(vec3(XM(nm), XM(nm + 1), XM(nm + 2)), a_nrm.xyz), dot(vec3(XM(nm + 3), XM(nm + 4), XM(nm + 5)), a_nrm.xyz),\n"
"                dot(vec3(XM(nm + 6), XM(nm + 7), XM(nm + 8)), a_nrm.xyz));\n"
"  if (dot(n, n) > 0.0) n = normalize(n);\n"
"  float P0 = uintBitsToFloat(XR(0x20)), P1 = uintBitsToFloat(XR(0x21)), P2 = uintBitsToFloat(XR(0x22));\n"
"  float P3 = uintBitsToFloat(XR(0x23)), P4 = uintBitsToFloat(XR(0x24)), P5 = uintBitsToFloat(XR(0x25));\n"
"  vec4 clip = XR(0x26) == 0u ? vec4(P0 * pv.x + P1 * pv.z, P2 * pv.y + P3 * pv.z, P4 * pv.z + P5, -pv.z)\n"
"                             : vec4(P0 * pv.x + P1, P2 * pv.y + P3, P4 * pv.z + P5, 1.0);\n"
"  float xs = uintBitsToFloat(XR(0x1A)), ys = uintBitsToFloat(XR(0x1B)), zs = uintBitsToFloat(XR(0x1C));\n"
"  float zo = uintBitsToFloat(XR(0x1F));\n"
"  gl_Position = vec4(clip.x * sign(xs), clip.y * sign(ys), (2.0 * zo / 16777215.0 - 1.0) * clip.w + 2.0 * zs / 16777215.0 * clip.z, clip.w);\n"
"  uint nchan = bits(XR(0x09), 0, 2);\n"
"  v_col0 = nchan >= 1u ? channel(0, a_col0, pv, n) : vec4(0.0);\n"
"  v_col1 = nchan >= 2u ? channel(1, a_col1, pv, n) : vec4(0.0);\n"
"  uint ntex = bits(XR(0x3F), 0, 4);\n"
"  v_tex0 = ntex > 0u ? texgen(0, a_pos.xyz, a_nrm.xyz, v_col0, v_col1, a_tm0.x) : vec3(0, 0, 1);\n"
"  v_tex1 = ntex > 1u ? texgen(1, a_pos.xyz, a_nrm.xyz, v_col0, v_col1, a_tm0.y) : vec3(0, 0, 1);\n"
"  v_tex2 = ntex > 2u ? texgen(2, a_pos.xyz, a_nrm.xyz, v_col0, v_col1, a_tm0.z) : vec3(0, 0, 1);\n"
"  v_tex3 = ntex > 3u ? texgen(3, a_pos.xyz, a_nrm.xyz, v_col0, v_col1, a_tm0.w) : vec3(0, 0, 1);\n"
"  v_tex4 = ntex > 4u ? texgen(4, a_pos.xyz, a_nrm.xyz, v_col0, v_col1, a_tm1.x) : vec3(0, 0, 1);\n"
"  v_tex5 = ntex > 5u ? texgen(5, a_pos.xyz, a_nrm.xyz, v_col0, v_col1, a_tm1.y) : vec3(0, 0, 1);\n"
"  v_tex6 = ntex > 6u ? texgen(6, a_pos.xyz, a_nrm.xyz, v_col0, v_col1, a_tm1.z) : vec3(0, 0, 1);\n"
"  v_tex7 = ntex > 7u ? texgen(7, a_pos.xyz, a_nrm.xyz, v_col0, v_col1, a_tm1.w) : vec3(0, 0, 1);\n"
"}\n";

static const char* const k_gx_fragment_shader =
GX_SHADER_COMMON
"in vec4 v_col0; in vec4 v_col1;\n"
"in vec3 v_tex0; in vec3 v_tex1; in vec3 v_tex2; in vec3 v_tex3;\n"
"in vec3 v_tex4; in vec3 v_tex5; in vec3 v_tex6; in vec3 v_tex7;\n"
"uniform sampler2D u_tex0, u_tex1, u_tex2, u_tex3, u_tex4, u_tex5, u_tex6, u_tex7;\n"
"out vec4 o_color;\n"
"vec3 coord(uint i) {\n"
"  return i == 0u ? v_tex0 : i == 1u ? v_tex1 : i == 2u ? v_tex2 : i == 3u ? v_tex3 :\n"
"         i == 4u ? v_tex4 : i == 5u ? v_tex5 : i == 6u ? v_tex6 : v_tex7;\n"
"}\n"
"vec4 sample_map(uint m, vec2 uv) {\n"
"  if (m == 0u) return texture(u_tex0, uv); if (m == 1u) return texture(u_tex1, uv);\n"
"  if (m == 2u) return texture(u_tex2, uv); if (m == 3u) return texture(u_tex3, uv);\n"
"  if (m == 4u) return texture(u_tex4, uv); if (m == 5u) return texture(u_tex5, uv);\n"
"  if (m == 6u) return texture(u_tex6, uv); return texture(u_tex7, uv);\n"
"}\n"
"vec4 swizzle(vec4 c, uint table) {\n"
"  uint lo = BP(0xF6 + int(table) * 2), hi = BP(0xF7 + int(table) * 2);\n"
"  return vec4(c[bits(lo, 0, 2)], c[bits(lo, 2, 2)], c[bits(hi, 0, 2)], c[bits(hi, 2, 2)]);\n"
"}\n"
"float s11(uint v) { return float(int(v << 21u) >> 21) / 255.0; }\n"
"vec4 tev_reg(int r) {  /* r: 0 PREV, 1-3 C0-C2 (initial values) */\n"
"  uint ra = BP(0xE0 + 2 * r), bg = BP(0xE1 + 2 * r);\n"
"  return vec4(s11(bits(ra, 0, 11)), s11(bits(bg, 12, 11)), s11(bits(bg, 0, 11)), s11(bits(ra, 12, 11)));\n"
"}\n"
"vec4 konst_reg(int k) {\n"
"  uint ra = KR(2 * k), bg = KR(2 * k + 1);\n"
"  return vec4(float(bits(ra, 0, 8)), float(bits(bg, 12, 8)), float(bits(bg, 0, 8)), float(bits(ra, 12, 8))) / 255.0;\n"
"}\n"
"vec3 kcolor(uint sel) {\n"
"  if (sel < 8u) return vec3(1.0 - float(sel) / 8.0);\n"
"  if (sel >= 12u && sel < 16u) return konst_reg(int(sel) - 12).rgb;\n"
"  if (sel >= 16u) { vec4 k = konst_reg(int(sel & 3u)); return vec3(k[int((sel - 16u) >> 2)]); }\n"
"  return vec3(0.0);\n"
"}\n"
"float kalpha(uint sel) {\n"
"  if (sel < 8u) return 1.0 - float(sel) / 8.0;\n"
"  if (sel >= 16u) { vec4 k = konst_reg(int(sel & 3u)); return k[int((sel - 16u) >> 2)]; }\n"
"  return 0.0;\n"
"}\n"
"bool acmp(float a, uint f, float ref) {\n"
"  if (f == 0u) return false; if (f == 1u) return a < ref; if (f == 2u) return a == ref; if (f == 3u) return a <= ref;\n"
"  if (f == 4u) return a > ref; if (f == 5u) return a != ref; if (f == 6u) return a >= ref; return true;\n"
"}\n"
"float q8(float v) { return floor(clamp(v, 0.0, 1.0) * 255.0 + 0.5); }\n"
"void main() {\n"
"  vec4 r[4];\n"
"  for (int i = 0; i < 4; i++) r[i] = tev_reg(i);\n"
"  int stages = int(bits(BP(0x00), 10, 4)) + 1;\n"
"  for (int s = 0; s < 16; s++) {\n"
"    if (s >= stages) break;\n"
"    uint order = BP(0x28 + s / 2) >> uint((s & 1) * 12);\n"
"    uint cenv = BP(0xC0 + 2 * s), aenv = BP(0xC1 + 2 * s);\n"
"    vec4 tex = vec4(0.0);\n"
"    if (bits(order, 6, 1) != 0u) {\n"
"      vec3 tc = coord(bits(order, 3, 3));\n"
"      tex = swizzle(sample_map(bits(order, 0, 3), tc.xy / (tc.z == 0.0 ? 1.0 : tc.z)), bits(aenv, 2, 2));\n"
"    }\n"
"    uint ch = bits(order, 7, 3);\n"
"    vec4 ras = ch == 0u ? v_col0 : ch == 1u ? v_col1 : vec4(0.0);\n"
"    ras = swizzle(clamp(ras, 0.0, 1.0), bits(aenv, 0, 2));\n"
"    uint ksel = BP(0xF6 + s / 2);\n"
"    vec3 kc = kcolor(bits(ksel, (s & 1) != 0 ? 14 : 4, 5));\n"
"    float ka = kalpha(bits(ksel, (s & 1) != 0 ? 19 : 9, 5));\n"
"    vec3 cin[16] = vec3[16](r[0].rgb, vec3(r[0].a), r[1].rgb, vec3(r[1].a), r[2].rgb, vec3(r[2].a), r[3].rgb, vec3(r[3].a),\n"
"                            tex.rgb, vec3(tex.a), ras.rgb, vec3(ras.a), vec3(1.0), vec3(0.5), kc, vec3(0.0));\n"
"    float ain[8] = float[8](r[0].a, r[1].a, r[2].a, r[3].a, tex.a, ras.a, ka, 0.0);\n"
"    /* color */\n"
"    vec3 ca = clamp(cin[bits(cenv, 12, 4)], 0.0, 1.0), cb = clamp(cin[bits(cenv, 8, 4)], 0.0, 1.0);\n"
"    vec3 cc = clamp(cin[bits(cenv, 4, 4)], 0.0, 1.0), cd = cin[bits(cenv, 0, 4)];\n"
"    uint cbias = bits(cenv, 16, 2), cop = bits(cenv, 18, 1), cscale = bits(cenv, 20, 2);\n"
"    vec3 cres;\n"
"    if (cbias != 3u) {\n"
"      vec3 l = mix(ca, cb, cc);\n"
"      cres = cd + (cop != 0u ? -l : l) + (cbias == 1u ? 0.5 : cbias == 2u ? -0.5 : 0.0);\n"
"      cres *= cscale == 0u ? 1.0 : cscale == 1u ? 2.0 : cscale == 2u ? 4.0 : 0.5;\n"
"    } else {\n"
"      uint mode = (cscale << 1) | cop; bool t;\n"
"      vec3 qa = vec3(q8(ca.r), q8(ca.g), q8(ca.b)), qb = vec3(q8(cb.r), q8(cb.g), q8(cb.b));\n"
"      if (mode < 6u) {\n"
"        float va = mode < 2u ? qa.r : mode < 4u ? qa.r + qa.g * 256.0 : qa.r + qa.g * 256.0 + qa.b * 65536.0;\n"
"        float vb = mode < 2u ? qb.r : mode < 4u ? qb.r + qb.g * 256.0 : qb.r + qb.g * 256.0 + qb.b * 65536.0;\n"
"        t = (mode & 1u) != 0u ? va == vb : va > vb;\n"
"        cres = cd + (t ? cc : vec3(0.0));\n"
"      } else {\n"
"        bvec3 bt = (mode & 1u) != 0u ? equal(qa, qb) : greaterThan(qa, qb);\n"
"        cres = cd + vec3(bt.x ? cc.r : 0.0, bt.y ? cc.g : 0.0, bt.z ? cc.b : 0.0);\n"
"      }\n"
"    }\n"
"    cres = bits(cenv, 19, 1) != 0u ? clamp(cres, 0.0, 1.0) : clamp(cres, -1024.0 / 255.0, 1023.0 / 255.0);\n"
"    /* alpha */\n"
"    float aa = clamp(ain[bits(aenv, 13, 3)], 0.0, 1.0), ab = clamp(ain[bits(aenv, 10, 3)], 0.0, 1.0);\n"
"    float ac = clamp(ain[bits(aenv, 7, 3)], 0.0, 1.0), ad = ain[bits(aenv, 4, 3)];\n"
"    uint abias = bits(aenv, 16, 2), aop = bits(aenv, 18, 1), ascale = bits(aenv, 20, 2);\n"
"    float ares;\n"
"    if (abias != 3u) {\n"
"      float l = mix(aa, ab, ac);\n"
"      ares = ad + (aop != 0u ? -l : l) + (abias == 1u ? 0.5 : abias == 2u ? -0.5 : 0.0);\n"
"      ares *= ascale == 0u ? 1.0 : ascale == 1u ? 2.0 : ascale == 2u ? 4.0 : 0.5;\n"
"    } else {\n"
"      uint mode = (ascale << 1) | aop; bool t;\n"
"      vec3 qa = vec3(q8(cin[bits(cenv, 12, 4)].r), q8(cin[bits(cenv, 12, 4)].g), q8(cin[bits(cenv, 12, 4)].b));\n"
"      if (mode >= 6u) t = (mode & 1u) != 0u ? q8(aa) == q8(ab) : q8(aa) > q8(ab);\n"
"      else t = (mode & 1u) != 0u ? q8(ca.r) == q8(cb.r) : q8(ca.r) > q8(cb.r);\n"
"      ares = ad + (t ? ac : 0.0);\n"
"    }\n"
"    ares = bits(aenv, 19, 1) != 0u ? clamp(ares, 0.0, 1.0) : clamp(ares, -1024.0 / 255.0, 1023.0 / 255.0);\n"
"    int cdst = int(bits(cenv, 22, 2)), adst = int(bits(aenv, 22, 2));\n"
"    r[cdst].rgb = cres; r[adst].a = ares;\n"
"  }\n"
"  vec4 o = clamp(r[0], 0.0, 1.0);\n"
"  /* alpha test */\n"
"  uint ac = BP(0xF3);\n"
"  float a8 = q8(o.a);\n"
"  bool t0 = acmp(a8, bits(ac, 16, 3), float(bits(ac, 0, 8))), t1 = acmp(a8, bits(ac, 19, 3), float(bits(ac, 8, 8)));\n"
"  uint lg = bits(ac, 22, 2);\n"
"  bool pass = lg == 0u ? (t0 && t1) : lg == 1u ? (t0 || t1) : lg == 2u ? (t0 != t1) : (t0 == t1);\n"
"  if (!pass) discard;\n"
"  uint cm1 = BP(0x42);\n"
"  if (bits(cm1, 8, 1) != 0u) o.a = float(bits(cm1, 0, 8)) / 255.0;\n"
"  else if (bits(BP(0x43), 0, 3) != 1u) o.a = 1.0;  /* EFB formats without alpha */\n"
"  o_color = o;\n"
"}\n";
