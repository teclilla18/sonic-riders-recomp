#!/usr/bin/env python3
"""embed_icons.py OUT.h ICON.png...: the touch-control icons (android/touch_icons) as one premultiplied RGBA atlas,
side by side, for render_vk.c. Standard library only (the setup's Python has no imaging module): decodes 8-bit
RGBA / RGB, non-interlaced PNGs. In the header: TOUCH_ATLAS_W/H, k_touch_atlas[], and per icon (in the order
given) its x offset, width and height."""
import os
import struct
import sys
import zlib


def read_png(path):
    return decode_png(open(path, "rb").read(), path)


def decode_png(data, path="PNG", premultiply=True):
    """(w, h, RGBA bytes); premultiplied alpha unless premultiply is False"""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit("%s: not a PNG" % path)
    pos, idat, w = 8, b"", 0
    while pos < len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if kind == b"IHDR":
            w, h, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", body)
            if depth != 8 or ctype not in (2, 6) or interlace:
                sys.exit("%s: needs 8-bit RGB/RGBA, not interlaced" % path)
            bpp = 4 if ctype == 6 else 3
        elif kind == b"IDAT":
            idat += body
        elif kind == b"IEND":
            break
    raw = zlib.decompress(idat)
    stride = w * bpp
    out = bytearray(w * h * 4)
    prev = bytearray(stride)
    p = 0
    for y in range(h):
        f = raw[p]
        line = bytearray(raw[p + 1:p + 1 + stride])
        p += 1 + stride
        for i in range(stride):  # PNG filters
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + ((a + b) >> 1)) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        for x in range(w):
            r, g, bl = line[x * bpp], line[x * bpp + 1], line[x * bpp + 2]
            al = line[x * bpp + 3] if bpp == 4 else 255
            o = (y * w + x) * 4  # premultiplied (the overlay blend is ONE, ONE_MINUS_SRC_ALPHA)
            if premultiply:
                r, g, bl = (r * al + 127) // 255, (g * al + 127) // 255, (bl * al + 127) // 255
            out[o:o + 4] = bytes((r, g, bl, al))
        prev = line
    return w, h, out


def main():
    out, pngs = sys.argv[1], sys.argv[2:]
    if not pngs or not all(os.path.isfile(p) for p in pngs):  # no pictures: the drawn icons (vk_touch.frag)
        os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
        open(out, "w").write("/* generated by tools/embed_icons.py: no pictures in android/touch_icons */\n#pragma once\n"
                             "#include <stdint.h>\n#define TOUCH_ATLAS_W 1\n#define TOUCH_ATLAS_H 1\n#define TOUCH_ICONS 0\n"
                             "static const uint16_t k_touch_icon[1][3] = {{0, 1, 1}};\n"
                             "static const uint8_t k_touch_atlas[4] = {0, 0, 0, 0};\n")
        print("embed_icons: no pictures (android/touch_icons): the touch controls use drawn icons")
        return
    icons = [read_png(p) for p in pngs]
    W, H = sum(i[0] for i in icons) + 2 * len(icons), max(i[1] for i in icons)
    atlas = bytearray(W * H * 4)
    x0, place = 0, []
    for w, h, px in icons:
        for y in range(h):
            atlas[(y * W + x0) * 4:(y * W + x0 + w) * 4] = px[y * w * 4:(y + 1) * w * 4]
        place.append((x0, w, h))
        x0 += w + 2  # a transparent gap: no bleeding between icons with linear filtering
    text = "/* generated by tools/embed_icons.py from android/touch_icons */\n#pragma once\n#include <stdint.h>\n"
    text += "#define TOUCH_ATLAS_W %d\n#define TOUCH_ATLAS_H %d\n#define TOUCH_ICONS %d\n" % (W, H, len(icons))
    text += "static const uint16_t k_touch_icon[%d][3] = {%s};  /* x, w, h */\n" % (
        len(icons), ", ".join("{%d, %d, %d}" % p for p in place))
    text += "static const uint8_t k_touch_atlas[%d] = {\n" % len(atlas)
    for i in range(0, len(atlas), 32):
        text += ",".join(str(b) for b in atlas[i:i + 32]) + ",\n"
    text += "};\n"
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    open(out, "w").write(text)
    print("embed_icons: %d icons, atlas %dx%d" % (len(icons), W, H))


if __name__ == "__main__":
    main()
