def load_socials():
    """socials.json at the branch root: the one place to add a social media account (see MAINTAINING.md)."""
    try:
        items = json.loads((ROOT / 'socials.json').read_text(encoding='utf-8'))
    except (OSError, ValueError) as e:
        raise SystemExit(f'socials.json: {e}')
    return [i for i in items if i.get('name') and str(i.get('url', '')).startswith('https://')]


def social_cards(items, reveal):
    cls = 'comm panel reveal' if reveal else 'comm panel'
    return '\n'.join(f'    <a class="{cls}" href="{E(i["url"])}" rel="me" data-social><h3>{E(i["name"])}</h3>'
                     f'<p>{E(i.get("about", ""))}</p><span class="go">Follow →</span></a>' for i in items)


def social_links(items):
    return ''.join(f'<a href="{E(i["url"])}" rel="me">{E(i["name"])}</a>' for i in items)


def page_meta(text):
    m = re.match(r'\s*<!--\s*(.*?)\s*-->\s*', text, re.S)
    meta = dict(re.findall(r'(\w+)="([^"]*)"', m[1])) if m else {}
    return meta, text[m.end():] if m else text


def render(name, body, meta, partials):
    title = meta.get('title', 'Riders Rebuilt')
    full_title = title if title.startswith('Riders Rebuilt') else f'{title} · Riders Rebuilt'
    desc = meta.get('description', 'Sonic Riders, running natively on Switch 2, Switch, PC, Android, Linux and iPhone. '
                                   'An unofficial fan port built from your own disc.')
    canonical = SITE + ('' if name == 'index.html' else name)
    share_image = SITE + meta.get('share_image', 'assets/img/switch2-poster.jpg')
    head = partials['head'].replace('{{title}}', E(full_title)).replace('{{description}}', E(desc)).replace(
        '{{canonical}}', canonical).replace('{{share_image}}', E(share_image))
    analytics = ('<meta name="referrer" content="no-referrer">' if meta.get('noanalytics')
                 else '<script src="assets/js/analytics.js" defer></script>')
    head = head.replace('{{analytics}}', analytics)
    if meta.get('noindex'):
        head += '\n<meta name="robots" content="noindex">'
    if name == '404.html':  # served at any missing URL, so pin relative links to the site root
        head = '<base href="/sonic-riders-recomp/">\n' + head
    socials = load_socials()
    body = body.replace('{{social_cards}}', '<div class="social-slot" data-socials="cards" hidden></div>\n' + social_cards(socials, name == 'index.html'))
    footer = partials['footer'].replace('{{social_links}}', '<span data-socials="links">' + social_links(socials) + '</span>')
    header = partials['header']
    active = meta.get('nav', '')
    if active:
        header = header.replace(f'data-nav="{active}"', f'data-nav="{active}" aria-current="page"')
    return (f'<!doctype html>\n<html lang="en">\n<head>\n{head}\n</head>\n<body class="page-{name[:-5]}">\n'
            f'<div class="bg" aria-hidden="true"></div>\n{header}\n<main id="main">\n{body}\n</main>\n{footer}\n'
            f'<script src="assets/js/site.js" defer></script>\n</body>\n</html>\n')


REDIRECTS = {'riders-plus.html': 'riders-rebuilt.html', 'riders-crosswake.html': 'riders-rebuilt.html', 'install-guide.html': 'install.html', 'update-guide.html': 'update.html'}


def build():
    snap = json.loads((ROOT / 'assets/data/snapshot.json').read_text(encoding='utf-8'))
    partials = {p.stem: p.read_text(encoding='utf-8') for p in (SRC / 'partials').glob('*.html')}
    stable = next((r for r in snap['releases'] if not r['prerelease']), {'tag': ''})
    blocks = {'platforms': platform_cards(snap), 'releases': release_cards(snap), 'progress': progress_block(snap),
              'overall': str(snap['progress']['overall']), 'stable_tag': E(stable['tag']),
              'downloads': f"{sum(a['downloads'] for r in snap['releases'] for a in r['assets']):,}"}
    for p in PLATFORMS:  # {{file:pc}} -> the current ZIP name (site.js refreshes it)
        a = find_asset(snap['releases'], p)[1]
        blocks['file:' + p['id']] = f'<span data-file="{p["id"]}">{E(a["name"] if a else p["fallback"])}</span>'
    for page in sorted((SRC / 'pages').glob('*.html')):
        meta, body = page_meta(page.read_text(encoding='utf-8'))
        for k, v in blocks.items():
            body = body.replace('{{' + k + '}}', v)
        left = [x for x in re.findall(r'\{\{[^}]+\}\}', body) if x != '{{social_cards}}']  # filled in render()
        if left:
            raise SystemExit(f'{page.name}: unknown placeholders {left}')
        (ROOT / page.name).write_text(render(page.name, body, meta, partials), encoding='utf-8', newline='\n')
    data = load_guide_data()
    for native in (False, True):
        g = data.guide(native)
        meta = dict(title=f'{g["platform"]} installation booklet', nav='guides',
                    description=f'Illustrated, beginner-friendly installation booklet for Sonic Riders on {g["platform"]} (Riders Rebuilt) ({g["edition"]}).')
        (ROOT / f'install-{g["mode"]}.html').write_text(render(f'install-{g["mode"]}.html', booklet(g), meta, partials),
                                                       encoding='utf-8', newline='\n')
    for old, new in REDIRECTS.items():
        (ROOT / old).write_text(
            f'<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Moved</title>'
            f'<meta http-equiv="refresh" content="0; url={new}"><link rel="canonical" href="{SITE}{new}">'
            f'<meta name="robots" content="noindex"></head><body><p>This guide moved to <a href="{new}">{new}</a>.</p></body></html>\n',
            encoding='utf-8', newline='\n')
    print('built', len(list((SRC / 'pages').glob('*.html'))) + 2, 'pages +', len(REDIRECTS), 'redirects')


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'build'
    if cmd in ('sync', 'all'):
        sync()
    if cmd in ('build', 'all'):
        build()
