def git(*args, binary=False):
    r = subprocess.run(['git', '-C', str(ROOT), *args], capture_output=True)
    if r.returncode:
        raise SystemExit('git ' + ' '.join(args) + ' failed: ' + r.stderr.decode(errors='replace'))
    return r.stdout if binary else r.stdout.decode('utf-8')


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'sonic-riders-recomp-site-build',
                                               'Accept': 'application/vnd.github+json'})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode('utf-8')


def parse_progress(make_progress, readme):
    areas = [dict(label=a, weight=int(w), done=int(d)) for a, w, d in
             re.findall(r'\(\s*"([^"]+)",\s*(\d+),\s*(\d+)\s*\)', make_progress.split('AREAS', 1)[1].split(']', 1)[0])]
    version = (re.search(r'^VERSION\s*=\s*"([^"]+)"', make_progress, re.M) or [None, ''])[1]
    updated = (re.search(r'^UPDATED\s*=\s*"([^"]+)"', make_progress, re.M) or [None, ''])[1]
    left = {}
    for line in readme.splitlines():
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) == 3 and cells[1].endswith('%'):
            left[cells[0]] = cells[2]
    for a in areas:
        a['left'] = left.get(a['label'], '')
    total = sum(a['weight'] for a in areas) or 1
    overall = round(sum(a['weight'] * a['done'] for a in areas) / total)
    return dict(version=version, updated=updated, overall=overall, areas=areas)


def slim_release(r):
    return dict(name=re.sub(r'\bRiders (?:Plus|Crosswake)\b', 'Riders Rebuilt', r.get('name') or r['tag_name'], flags=re.I), tag=r['tag_name'], prerelease=r['prerelease'],
                date=(r.get('published_at') or '')[:10], url=r['html_url'],
                assets=[dict(name=a['name'], url=a['browser_download_url'], size=a['size'],
                             downloads=a['download_count']) for a in r.get('assets', [])])


def sync():
    git('fetch', '--quiet', 'origin', 'main')
    head = git('rev-parse', '--short', MAIN).strip()
    # Booklet text
    (SRC / 'vendor').mkdir(parents=True, exist_ok=True)
    (SRC / 'vendor/console_guide_data.py').write_bytes(git('show', MAIN + ':tools/console_guide_data.py', binary=True))
    # Approved pictures
    guard = git('show', MAIN + ':tools/check_no_game_data.py')
    own = dict(re.findall(r'"([^"]+)":\s*"([0-9a-f]{40})"', guard))
    pics = list(IMAGES)
    for name in git('ls-tree', '--name-only', MAIN, GUIDE_PICTURES).split():
        if name.endswith(('.svg', '.png')):
            pics.append((name, 'assets/guide/' + name.rsplit('/', 1)[1]))
    approved = []
    for src, dst in pics:
        data = git('show', f'{MAIN}:{src}', binary=True)
        sha = hashlib.sha1(data).hexdigest()
        if src.endswith(('.jpg', '.png')) and own.get(src) != sha:
            raise SystemExit(f'{src}: SHA-1 {sha} is not approved on main (OWN_ART). Not copied; ask the user.')
        out = ROOT / dst
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(data)
        approved.append(f'{sha}  {dst}  (from main:{src})')
    lst = ROOT / 'tools/approved_images.txt'
    keep = [l for l in lst.read_text().splitlines() if l.strip() and '(from main:' not in l] if lst.exists() else []
    lst.write_text('\n'.join(keep + sorted(approved, key=lambda l: l.split('  ')[1])) + '\n')
    # Releases + progress snapshot
    releases = [slim_release(r) for r in json.loads(fetch(f'https://api.github.com/repos/{REPO}/releases?per_page=40'))
                if not r.get('draft')]
    progress = parse_progress(git('show', MAIN + ':tools/make_progress.py'), git('show', MAIN + ':README.md'))
    snap = dict(main=head, releases=releases, progress=progress)
    (ROOT / 'assets/data').mkdir(parents=True, exist_ok=True)
    (ROOT / 'assets/data/snapshot.json').write_text(json.dumps(snap, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    print(f'synced from main {head}: {len(pics)} pictures, {len(releases)} releases, overall {progress["overall"]}%')


