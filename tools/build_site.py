E = html.escape


def md_inline(s):
    """The small Markdown vocabulary used by the booklet data and the README table."""
    tokens = []

    def stash(m):
        tokens.append('<code>' + E(m[1]) + '</code>')
        return f'\x01{len(tokens) - 1}\x02'
    s = re.sub(r'`([^`]+)`', stash, s)
    s = E(s, quote=False)
    def link(m):  # relative links in main's docs point at files beside them in docs/
        href = m[2] if re.match(r'(https?:|#|mailto:)', m[2]) else f'{GH}/blob/main/docs/{m[2]}'
        return f'<a href="{href}">{m[1]}</a>'
    s = re.sub(r'\[([^\]]+)\]\(([^)\s]+)\)', link, s)
    s = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', s)
    s = re.sub(r'(?<![\w/&])#(\d+)\b', lambda m: f'<a href="{GH}/issues/{m[1]}">#{m[1]}</a>', s)
    s = re.sub(r'\x01(\d+)\x02', lambda m: tokens[int(m[1])], s)
    for text in ['Select disc…', 'Open Output Folder', 'BUILD AND INSTALL', 'Refresh', 'Other…', 'Eject SD card',
                 'Extract All…', 'Extract', 'Open', 'Copy the disc image too', 'Quit Game',
                 'Read shader compiler license', 'I accept the Android SDK License']:
        s = s.replace('<strong>' + text + '</strong>', '<strong class="k-btn">' + text + '</strong>')
    for text in ['Done', 'INSTALLATION COMPLETE', 'INSTALL FAILED', 'Safe to remove the SD card now.']:
        s = s.replace('<strong>' + text + '</strong>', '<strong class="k-screen">' + text + '</strong>')
    return s


def fmt_size(n):
    return f'{n / 1048576:.1f} MB' if n >= 1048576 else f'{max(1, round(n / 1024))} KB'


def fmt_date(d):
    if not d:
        return ''
    months = 'Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec'.split()
    y, m, dd = d.split('-')
    return f'{months[int(m) - 1]} {int(dd)}, {y}'


def find_asset(releases, p):
    for r in releases:
        if r['prerelease'] != (p['channel'] == 'alpha'):
            continue
        for a in r['assets']:
            if re.search(p['pattern'], a['name']):
                return r, a
    return None, None


